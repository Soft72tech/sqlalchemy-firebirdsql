class FirebirdDDLCompiler(compiler.DDLCompiler):
    def get_column_specification(self, column, **kwargs):
        colspec = self.preparer.format_column(column)

        impl_type = column.type.dialect_impl(self.dialect)
        if isinstance(impl_type, TypeDecorator):
            impl_type = impl_type.impl

        has_identity = column.identity is not None

        # TODO: refactor
        if (
            column.primary_key
            and column.autoincrement is True
            and not has_identity
            and (column.default is None or (isinstance(column.default, Sequence) and column.default.optional))
            and self.dialect.supports_identity_columns
        ):
            colspec += " INTEGER GENERATED BY DEFAULT AS IDENTITY"
        else:
            colspec += " " + self.dialect.type_compiler_instance.process(
                column.type,
                type_expression=column,
                identifier_preparer=self.preparer,
            )
            default_ = self.get_column_default_string(column)
            if default_ is not None:
                colspec += " DEFAULT " + default_

            if column.computed is not None:
                colspec += " " + self.process(column.computed)
            if has_identity:
                colspec += " " + self.process(column.identity)

            if not column.nullable and not has_identity:
                colspec += " NOT NULL"
            elif column.nullable and has_identity:
                colspec += " NULL"

        return colspec

    def visit_create_index(self, create, include_schema=False, include_table_schema=True, **kw):
        index = create.element
        self._verify_index_table(index)
        preparer = self.preparer
        text = ["CREATE"]
        if index.unique:
            text.append("UNIQUE")

        if index.dialect_options["firebird.firebirdsql"].get("descending"):
            text.append("DESCENDING")

        # if create.if_not_exists:
        #     text.append("IF NOT EXISTS")

        text.append(
            "INDEX %s ON %s "
            % (
                self._prepared_index_name(index, include_schema=include_schema),
                preparer.format_table(index.table, use_schema=include_table_schema),
            )
        )

        if index.expressions is None:
            raise exc.CompileError(
                "CREATE INDEX requires at least one column or expression."
            )

        first_expression = (
            index.expressions[0]
            if len(index.expressions) > 0
            else index.expressions
        )

        if isinstance(first_expression, expression.ColumnClause):
            expression_str = ", ".join(
                    self.sql_compiler.process(
                        expr, include_table=False, literal_binds=True
                    )
                    for expr in index.expressions
                )
            text.append(f"({expression_str})")
        else:
            expression_str = "||".join(
                self.sql_compiler.process(
                    expr, include_table=False, literal_binds=True
                )
                for expr in index.expressions
            )
            text.append(f"COMPUTED BY ({expression_str})")

        whereclause = index.dialect_options["firebird.firebirdsql"].get("where")
        if whereclause is not None:
            where_compiled = self.sql_compiler.process(whereclause, include_table=False, literal_binds=True)
            text.append(f"WHERE {where_compiled}")
        return " ".join(text)

    def post_create_table(self, table):
        table_options = []
        on_commit = table.dialect_options["firebird.firebirdsql"].get("on_commit")
        if on_commit:
            table_options.append(f"ON COMMIT {on_commit}")
        return " " + ", ".join(table_options)

    def visit_computed_column(self, generated, **kw):
        if generated.persisted is not None:
            raise exc.CompileError(
                "Firebird computed columns do not support a persistence "
                "method setting; set the 'persisted' flag to None for "
                "Firebird support."
            )

        return "GENERATED ALWAYS AS (%s)" % self.sql_compiler.process(
            generated.sqltext, include_table=False, literal_binds=True
        )

    def get_identity_options(self, identity_options):
        text = []
        if identity_options.start is not None:
            start = identity_options.start
            text.append("START WITH %d" % start)

        if identity_options.increment is not None:
            text.append("INCREMENT BY %d" % identity_options.increment)

        return " ".join(text)

    def visit_identity_column(self, identity, **kw):
        kind = "ALWAYS" if identity.always else "BY DEFAULT"
        text = f"GENERATED {kind} AS IDENTITY"

        options = self.get_identity_options(identity)
        if options:
            text += f" ({options})"

        return text


